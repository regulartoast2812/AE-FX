#!/usr/bin/env python3
"""Derive what each host function requires, from its own guard clauses.

The jsx functions state their requirements in code - "No layers selected",
"No keyframes selected" - so the table is read out of the implementation
rather than decided by hand. Re-run after adding host functions.

    python3 scripts/derive-command-requirements.py
"""
import re, pathlib, json

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = (ROOT / "jsx" / "timeline.jsx").read_text()

# Only requirements the code states plainly. "needs a comp" is deliberately not
# derived: there is essentially always a comp open, so dimming on it would grey
# out most of the list for nothing.
RULES = [
    ("keyframes", r'No keyframes selected|No selected keyframes|No properties selected|Select at least one keyframe'),
    ("layers",    r'No layers selected|Select at least one layer|No layer selected'),
    ("masks",     r'No masks?\b'),
]

out = {}
for name, body in re.findall(r"\nfunction (\w+)\([^)]*\)\s*\{(.*?)\n\}", SRC, re.S):
    head = body[:800]
    found = [tag for tag, pat in RULES if re.search(pat, head, re.I)]
    # keyframes implies a selection; recording both would dim twice for one cause
    if "keyframes" in found and "layers" in found:
        found = ["keyframes"]
    if found:
        out[name] = found[0]

lines = [
    "// Generated by scripts/derive-command-requirements.py - do not edit by hand.",
    "//",
    "// What each host function requires, read out of its own guard clauses in",
    "// jsx/timeline.jsx rather than decided by hand. A command whose requirement",
    "// the current selection does not meet is dimmed in the Functions list.",
    "//",
    "// Only requirements the code states plainly are here. Text-only or",
    "// shape-only commands are not: almost none of them say so, and a wrongly",
    "// greyed button is worse than none.",
    "const TNT_FUNCTION_REQUIREMENTS = {",
]
for key in sorted(out):
    lines.append(f'  {json.dumps(key)}: {json.dumps(out[key])},')
lines.append("};")
lines.append("")
(ROOT / "src" / "js" / "06-command-requirements.js").write_text("\n".join(lines))
print(f"{len(out)} host functions mapped")
by = {}
for v in out.values():
    by[v] = by.get(v, 0) + 1
for k, v in sorted(by.items(), key=lambda kv: -kv[1]):
    print(f"  {v:>4}  {k}")
